"""Main comparison LaTeX tables, one per environment: columns = theta_exec, row blocks = theta_plan, rows in a
block = the 7 planners; mean reward (+- 1 SE over the 200 episodes), no averaging. N = 2000, robust planners at TV eps 0.2, each plan tuned
separately. Best planner per (theta_plan, theta_exec) in bold; missing runs print as "--".
    python experiments/results/main_comparision/make_table.py   -> main_comparison_<env>.tex"""
import glob
import os
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
# env -> (title, theta name in the header)
ENVS = {"frozen_lake": ("FrozenLake", "slip rate"), "cliffwalking": ("CliffWalking", "slip rate"),
        "gambler": ("Gambler", "$p_h$")}
LANDSCAPE = {"gambler"}   # 8 theta_exec columns do not fit a portrait page at a readable size
ALGOS = [("uct", "UCT"), ("stochastic-power-uct", "Power-UCT"), ("robust-uct", "Robust-UCT"),
         ("gs-power-uct", "GS-Power"), ("gsf-power-uct", "GSF-Power"),
         ("gs-robust-uct", "GS-Robust"), ("gsf-robust-uct", "GSF-Robust")]


def load():
    parts = []
    for f in glob.glob(os.path.join(HERE, "*", "plan*", "run", "**", "summary.csv"), recursive=True):
        s = pd.read_csv(f).dropna(subset=["theta_exec"])
        s["env"] = os.path.relpath(f, HERE).split(os.sep)[0]
        parts.append(s[["env", "config_id", "theta_plan", "theta_exec", "mean_reward", "reward_se"]])
    return pd.concat(parts).round({"theta_plan": 3, "theta_exec": 3})


def cell(m, se, best):
    if pd.isna(m):
        return "--"
    txt = f"{m:.3f}" + r"{\scriptsize$\pm$" + f"{se:.3f}".lstrip("0") + "}"
    return r"\textbf{" + txt + "}" if best else txt


df = load()
names = [a for a, _ in ALGOS]
for env, (title, theta) in ENVS.items():
    e = df[df.env == env]
    m = e.pivot_table(index=["theta_plan", "config_id"], columns="theta_exec", values="mean_reward")
    se = e.pivot_table(index=["theta_plan", "config_id"], columns="theta_exec", values="reward_se")
    plans = sorted(e.theta_plan.unique())
    execs = list(m.columns)
    full = pd.MultiIndex.from_product([plans, names])
    m, se = m.reindex(full), se.reindex(full)
    missing = sorted({(p, n) for p in plans for a, n in ALGOS if m.loc[(p, a)].isna().all()})
    env_tab = "sidewaystable" if env in LANDSCAPE else "table"
    lines = [f"% generated by experiments/results/main_comparision/make_table.py -- needs \\usepackage{{booktabs,multirow,adjustbox,amsmath"
             + (",rotating" if env in LANDSCAPE else "") + "}",
             rf"\begin{{{env_tab}}}" + ("" if env in LANDSCAPE else "[t]"), r"\centering", r"\small",
             rf"\caption{{Main comparison on {title}: mean reward ($\pm$1 SE over 200 episodes) for each "
             rf"$\theta_{{\text{{plan}}}}$ (row blocks) and $\theta_{{\text{{exec}}}}$ (columns, {theta}), $N = 2000$ "
             rf"simulations per search, robust planners with TV budget $\varepsilon = 0.2$. Best planner per "
             rf"$\theta_{{\text{{plan}}}}$ and $\theta_{{\text{{exec}}}}$ in bold"
             + ("; -- = not run" if missing else "") + ".}",
             rf"\label{{tab:main-{env.replace('_', '-')}}}",
             r"\begin{adjustbox}{max width=\linewidth}",
             r"\begin{tabular}{ll" + "c" * len(execs) + "}", r"\toprule",
             r" & & \multicolumn{" + str(len(execs)) + r"}{c}{$\theta_{\text{exec}}$ (" + theta + r")} \\",
             r"\cmidrule(l){3-" + str(2 + len(execs)) + "}",
             r"$\theta_{\text{plan}}$ & Planner & " + " & ".join(f"{t:g}" for t in execs) + r" \\",
             r"\midrule"]
    for i, p in enumerate(plans):
        block, block_se = m.loc[p], se.loc[p]
        best = block.max()
        for j, (a, n) in enumerate(ALGOS):
            cells = [cell(block.loc[a, t], block_se.loc[a, t], np.isclose(block.loc[a, t], best[t])) for t in execs]
            lead = (r"\multirow{" + str(len(ALGOS)) + r"}{*}{" + f"{p:g}" + "}") if j == 0 else ""
            lines.append(f"{lead} & {n} & " + " & ".join(cells) + r" \\")
        lines.append(r"\midrule" if i < len(plans) - 1 else r"\bottomrule")
    lines += [r"\end{tabular}", r"\end{adjustbox}", rf"\end{{{env_tab}}}"]
    out = os.path.join(HERE, f"main_comparison_{env}.tex")
    open(out, "w").write("\n".join(lines) + "\n")
    print("saved", out, f"({len(plans)} plans x {len(ALGOS)} planners, {len(execs)} exec; missing: {missing or 'none'})")
